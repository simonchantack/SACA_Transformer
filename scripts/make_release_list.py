def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main() -> None:
    files = []
    for p in sorted(ROOT.rglob("*")):
        if not p.is_file() or p.name in SKIP_FILES:
            continue
        rel = p.relative_to(ROOT)
        if any(part in SKIP_DIRS for part in rel.parts) or p.suffix == ".pyc":
            continue
        files.append(rel.as_posix())
    lines = ["# RELEASE_FILES.md", "",
             "Release list confirmed by Simon 2026-10-27 after his review (RULES §25). sha256 of every file under `final/`; generated by "
             "`scripts/make_release_list.py`. Excluded files and the reason for each follow.", "",
             f"## Included ({len(files)} files)", "", "| File | sha256 |", "|---|---|"]
    for rel in files:
        lines.append(f"| `{rel}` | {sha(ROOT / rel)} |")
    lines += ["", "## Excluded", "", "| File | Reason |", "|---|---|"]
    lines += [f"| {a} | {b} |" for a, b in EXCLUDED]
    lines += ["", "## Proposed external artifacts (frozen, hashed in their own folders)", "", "| Artifact | Note |", "|---|---|"]
    lines += [f"| {a} | {b} |" for a, b in PROPOSED_EXTERNAL]
    lines += ["", "## Notes on individual files", "", "| File | Note |", "|---|---|"]
    lines += [f"| `{a}` | {b} |" for a, b in FILE_NOTES]
    (ROOT / "RELEASE_FILES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(len(files), "files listed")


if __name__ == "__main__":
    main()
