"""Write RELEASE_FILES.md: the release file list with sha256 and notes on individual files.

The list was confirmed by Simon on 2026-10-27 after his review. Run from anywhere: ``python scripts/make_release_list.py``.
"""
from __future__ import annotations

import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKIP_DIRS = {".git", "__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache", ".venv", "regenerated", "runs", "saca_rul.egg-info"}
SKIP_FILES = {"RELEASE_FILES.md"}

FILE_NOTES = [
    ("figures/fig_saca_architecture.pdf", "manuscript Fig. 1 (SACA architecture): first draft generated as an editable PowerPoint slide by a script in the project workspace "
     "(not in this repository) from a specification derived from the code; edited by the authors in PowerPoint, with further edits by an agent "
     "under the authors' instructions (a block merge, legend and label wording, line styles and layout); exported by the authors to PDF "
     "(page 1 copied unchanged); no script in this repository generates it; checked against the code and results/shapes/d4_shapes."),
    ("docs/REPRODUCIBILITY.md", "technical details behind the README: frozen environment, determinism, reproduction checks, hash checks, test-set guard, pinned upstream code."),
    ("LICENSE", "MIT licence of the release code (Simon Chan Tack and Subash Chandra Pakhrin); vendored upstream code keeps its own licence files."),
    ("CITATION.cff", "Citation metadata (Citation File Format 1.2.0)."),
]


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main() -> None:
    files = []
    for p in sorted(ROOT.rglob("*")):
        if not p.is_file() or p.name in SKIP_FILES:
            continue
        rel = p.relative_to(ROOT)
        if any(part in SKIP_DIRS for part in rel.parts) or p.suffix == ".pyc":
            continue
        files.append(rel.as_posix())
    lines = ["# RELEASE_FILES.md", "",
             "sha256 of every file under `final/`; generated by "
             "`scripts/make_release_list.py`. A note on files that are not included follows.", "",
             f"## Included ({len(files)} files)", "", "| File | sha256 |", "|---|---|"]
    for rel in files:
        lines.append(f"| `{rel}` | {sha(ROOT / rel)} |")
    lines += ["", "## Excluded", "", "Licensed third-party papers and internal working files are not included."]
    lines += ["", "## Notes on individual files", "", "| File | Note |", "|---|---|"]
    lines += [f"| `{a}` | {b} |" for a, b in FILE_NOTES]
    (ROOT / "RELEASE_FILES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(len(files), "files listed")


if __name__ == "__main__":
    main()
